def rodrigues(aa):
    """axis-angle [...,3] -> rotation matrices [...,3,3]"""
    import numpy as np
    aa = np.asarray(aa, dtype=np.float64)
    th = np.linalg.norm(aa, axis=-1, keepdims=True)
    k = aa / np.maximum(th, 1e-12)
    K = np.zeros(aa.shape[:-1] + (3, 3))
    K[..., 0, 1], K[..., 0, 2], K[..., 1, 2] = -k[..., 2], k[..., 1], -k[..., 0]
    K[..., 1, 0], K[..., 2, 0], K[..., 2, 1] = k[..., 2], -k[..., 1], k[..., 0]
    th = th[..., None]
    return np.eye(3) + np.sin(th) * K + (1 - np.cos(th)) * (K @ K)


def quat_from_aa(aa):
    """axis-angle [...,3] -> unit quaternions [...,4] as (x, y, z, w)"""
    import numpy as np
    aa = np.asarray(aa, dtype=np.float64)
    th = np.linalg.norm(aa, axis=-1, keepdims=True)
    k = aa / np.maximum(th, 1e-12)
    return np.concatenate([k * np.sin(th / 2), np.cos(th / 2)], -1)


def quat_to_mat(q):
    import numpy as np
    q = q / np.linalg.norm(q, axis=-1, keepdims=True)
    x, y, z, w = q[..., 0], q[..., 1], q[..., 2], q[..., 3]
    R = np.empty(q.shape[:-1] + (3, 3))
    R[..., 0, 0] = 1 - 2 * (y * y + z * z); R[..., 0, 1] = 2 * (x * y - z * w); R[..., 0, 2] = 2 * (x * z + y * w)
    R[..., 1, 0] = 2 * (x * y + z * w); R[..., 1, 1] = 1 - 2 * (x * x + z * z); R[..., 1, 2] = 2 * (y * z - x * w)
    R[..., 2, 0] = 2 * (x * z - y * w); R[..., 2, 1] = 2 * (y * z + x * w); R[..., 2, 2] = 1 - 2 * (x * x + y * y)
    return R


def mat_to_aa(R):
    """rotation matrices [...,3,3] -> axis-angle (via quaternion, robust near pi)"""
    import numpy as np
    from scipy.spatial.transform import Rotation
    sh = R.shape[:-2]
    return Rotation.from_matrix(R.reshape(-1, 3, 3)).as_rotvec().reshape(sh + (3,))


def slerp(q0, q1, t):
    """per-row slerp of unit quaternions [...,4], shortest path; t broadcastable [...,1]"""
    import numpy as np
    d = np.sum(q0 * q1, -1, keepdims=True)
    q1 = np.where(d < 0, -q1, q1); d = np.abs(d)
    th = np.arccos(np.clip(d, -1, 1)); s = np.sin(th)
    small = s < 1e-6
    a = np.where(small, 1 - t, np.sin((1 - t) * th) / np.where(small, 1, s))
    b = np.where(small, t, np.sin(t * th) / np.where(small, 1, s))
    q = a * q0 + b * q1
    return q / np.linalg.norm(q, axis=-1, keepdims=True)


def global_transforms(Rloc, joints, parents, root_t=None):
    """Rloc [n,J,3,3] local rotations, joints [J,3] rest joints -> relative transforms A [n,J,4,4] (LBS)."""
    import numpy as np
    n, J = Rloc.shape[:2]
    G = np.zeros((n, J, 4, 4)); G[..., 3, 3] = 1
    for j in range(J):
        p = parents[j]
        L = np.zeros((n, 4, 4)); L[:, :3, :3] = Rloc[:, j]; L[:, 3, 3] = 1
        L[:, :3, 3] = joints[j] - (joints[p] if p >= 0 else 0)
        if p < 0 and root_t is not None:
            L[:, :3, 3] += root_t
        G[:, j] = L if p < 0 else G[:, p] @ L
    A = G.copy()
    A[..., :3, 3] = G[..., :3, 3] - np.einsum("njab,jb->nja", G[..., :3, :3], joints)
    return A, G


def lbs_apply(A, idx, w, v):
    """A [n,J,4,4]; idx [V,K] joints; w [V,K] weights; v [V,3] rest -> [n,V,3]"""
    import numpy as np
    M = np.einsum("vk,nvkab->nvab", w, A[:, idx])          # [n,V,4,4]
    return np.einsum("nvab,vb->nva", M[..., :3, :3], v) + M[..., :3, 3]


class SmplxNP:
    """Exact SMPL-X forward in numpy (betas = expression = 0), same formula as smplx.lbs, with pose correctives."""

    def __init__(self, path=MODEL_DEFAULT):
        import numpy as np
        M = np.load(path, allow_pickle=False)
        self.vt = M["v_template"].astype(np.float64)
        self.J = M["J_regressor"].astype(np.float64) @ self.vt
        self.W = M["weights"].astype(np.float64)
        par = M["kintree_table"][0].astype(np.int64); par[0] = -1
        self.parents = par
        self.posedirs = M["posedirs"].reshape(-1, M["posedirs"].shape[-1]).astype(np.float32)  # [V*3, 486]
        self.hands_mean = np.concatenate([M["hands_meanl"], M["hands_meanr"]]).astype(np.float64)
        self.f = M["f"].astype(np.int64)

    def full_pose(self, body_pose, global_orient=None):
        """[n,63] body pose -> [n,55,3] with jaw/eyes 0 and hands at the SMPL-X mean (flat_hand_mean=False)."""
        import numpy as np
        n = len(body_pose)
        P = np.zeros((n, 55, 3))
        if global_orient is not None:
            P[:, 0] = global_orient
        P[:, 1:22] = np.asarray(body_pose).reshape(n, 21, 3)
        P[:, 25:55] = self.hands_mean.reshape(30, 3)
        return P

    def forward(self, pose55, correctives=True, batch=48):
        import numpy as np
        out = np.empty((len(pose55), len(self.vt), 3))
        for s in range(0, len(pose55), batch):
            R = rodrigues(pose55[s:s + batch])
            v = np.broadcast_to(self.vt, (len(R),) + self.vt.shape).copy()
            if correctives:
                feat = (R[:, 1:] - np.eye(3)).reshape(len(R), -1).astype(np.float32)
                v += (feat @ self.posedirs.T).reshape(len(R), -1, 3)
            A, _ = global_transforms(R, self.J, self.parents)
            T = np.einsum("vj,njk->nvk", self.W, A.reshape(len(R), 55, 16)).reshape(len(R), -1, 4, 4)
            out[s:s + batch] = np.einsum("nvab,nvb->nva", T[..., :3, :3], v) + T[..., :3, 3]
        return out


