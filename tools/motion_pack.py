LEGS = {"L": (1, 4, 7, 10), "R": (2, 5, 8, 11)}               # hip, knee, ankle, foot (SMPL-X order)


def rot_x(a):
    import numpy as np
    a = np.asarray(a, dtype=np.float64); c, s_ = np.cos(a), np.sin(a)
    R = np.zeros(a.shape + (3, 3)); R[..., 0, 0] = 1
    R[..., 1, 1] = c; R[..., 1, 2] = -s_; R[..., 2, 1] = s_; R[..., 2, 2] = c
    return R


def rot_y(a):
    import numpy as np
    a = np.asarray(a, dtype=np.float64); c, s_ = np.cos(a), np.sin(a)
    R = np.zeros(a.shape + (3, 3)); R[..., 1, 1] = 1
    R[..., 0, 0] = c; R[..., 0, 2] = s_; R[..., 2, 0] = -s_; R[..., 2, 2] = c
    return R


def rot_z(a):
    import numpy as np
    a = np.asarray(a, dtype=np.float64); c, s_ = np.cos(a), np.sin(a)
    R = np.zeros(a.shape + (3, 3)); R[..., 2, 2] = 1
    R[..., 0, 0] = c; R[..., 0, 1] = -s_; R[..., 1, 0] = s_; R[..., 1, 1] = c
    return R


def knee_for_distance(u0, v0, d, iters=60):
    """knee flexion theta (rad, >= 0) with |u0 + Rx(theta) v0| = d (bisection; theta=0 if d is out of reach)."""
    import numpy as np
    lo = np.zeros_like(d); hi = np.full_like(d, np.radians(170))
    f = lambda th: np.linalg.norm(u0 + np.einsum("nab,b->na", rot_x(th), v0), axis=1) - d
    over = f(lo) < 0                                           # target farther than the straight leg
    for _ in range(iters):
        mid = (lo + hi) / 2; fm = f(mid)
        lo = np.where(fm > 0, mid, lo); hi = np.where(fm > 0, hi, mid)
    th = (lo + hi) / 2
    th[over] = 0.0
    return th, over


def leg_ik(Rp, P, J, side, ankle_target, foot_yaw):
    """Two-bone IK with the foot flat on the floor at yaw foot_yaw and the knee over the toes.
    Rp [n,3,3] pelvis world rotation, P [n,3] pelvis world position (pelvis rest joint at the origin).
    Returns local rotations (hip, knee, ankle) [n,3,3] each, knee angle, overextension flags."""
    import numpy as np
    h, k, a, _ = LEGS[side]
    H = P + np.einsum("nab,b->na", Rp, J[h] - J[0])
    t = ankle_target - H; d = np.linalg.norm(t, axis=1); th = t / d[:, None]
    u0 = J[k] - J[h]; v0 = J[a] - J[k]
    theta, over = knee_for_distance(u0, v0, d)
    Rk = rot_x(theta)
    w = u0 + np.einsum("nab,b->na", Rk, v0); wh = w / np.linalg.norm(w, axis=1, keepdims=True)
    k0 = u0[None] - np.sum(u0[None] * wh, 1, keepdims=True) * wh; k0 /= np.linalg.norm(k0, axis=1, keepdims=True)
    fwd = np.stack([np.sin(foot_yaw), np.zeros_like(foot_yaw), np.cos(foot_yaw)], 1)
    kd = fwd - np.sum(fwd * th, 1, keepdims=True) * th; kd /= np.linalg.norm(kd, axis=1, keepdims=True)
    Bt = np.stack([th, kd, np.cross(th, kd)], -1); Bw = np.stack([wh, k0, np.cross(wh, k0)], -1)
    RhW = Bt @ np.swapaxes(Bw, 1, 2)
    Rh = np.swapaxes(Rp, 1, 2) @ RhW
    Ra = np.swapaxes(RhW @ Rk, 1, 2) @ rot_y(foot_yaw)
    return Rh, Rk, Ra, theta, over


