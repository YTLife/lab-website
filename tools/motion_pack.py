def read_pack2(path):
    """Independent reader for hmmh-motion-2 (section offsets recomputed from the header, 4-byte padding)."""
    import numpy as np
    buf = open(path, "rb").read()
    (hl,) = struct.unpack_from("<I", buf, 0)
    if hl % 4:
        raise ValueError("headerLen not a multiple of 4")
    h = json.loads(buf[4:4 + hl].decode("utf-8"))
    V, T, F, J = h["vertexCount"], h["faceCount"], h["frames"], h["jointCount"]
    o = 4 + hl
    def take(dtype, count):
        nonlocal o
        arr = np.frombuffer(buf, dtype, count, o)
        o += arr.nbytes; o += (-o) % 4
        return arr
    rest = take("<u2", V * 3).reshape(V, 3)
    faces = take("<u2", T * 3).reshape(T, 3).astype(np.int64)
    sidx = take("u1", V * 4).reshape(V, 4)
    sw = take("u1", V * 4).reshape(V, 4).astype(np.float64)
    q = take("<i2", F * J * 4).reshape(F, J, 4).astype(np.float64) / 32767
    rt = take("<i2", F * 3).reshape(F, 3).astype(np.float64) / 1000
    if o != len(buf):
        raise ValueError(f"size mismatch: parsed {o}, file {len(buf)}")
    q /= np.linalg.norm(q, axis=-1, keepdims=True)
    return {"header": h, "rest": np.asarray(h["restOffset"]) + rest * np.asarray(h["restScale"]), "faces": faces,
            "skinIndex": sidx, "skinWeight": sw, "quats": q, "root": rt}



