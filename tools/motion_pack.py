# ----------------------------------------------------------------------------------------------- reading
def read_pack(path):
    """Independent reader for hmmh-motion-1. Returns (header dict, faces [T,3] int, frames [F,V,3] float64 m)."""
    import numpy as np
    buf = open(path, "rb").read()
    (hlen,) = struct.unpack_from("<I", buf, 0)
    if hlen % 4:
        raise ValueError("headerLen not a multiple of 4")
    header = json.loads(buf[4:4 + hlen].decode("utf-8"))
    T, V, F = header["faceCount"], header["vertexCount"], header["frames"]
    o = 4 + hlen
    faces = np.frombuffer(buf, "<u2", T * 3, o).reshape(T, 3).astype(np.int64)
    o += T * 6
    q = np.frombuffer(buf, "<u2", F * V * 3, o).reshape(F, V, 3)
    o += F * V * 6
    if o != len(buf):
        raise ValueError(f"trailing bytes: expected {o}, file {len(buf)}")
    frames = np.asarray(header["offset"]) + q.astype(np.float64) * np.asarray(header["scale"])
    return header, faces, frames


def load_source(src):
    import numpy as np
    man = json.load(open(os.path.join(src, "manifest.json")))
    act = man["actions"]["G07"]
    q = act["quantization"]
    faces = np.fromfile(os.path.join(src, man["model"]["topology"]["file"]), "<u2").reshape(-1, 3).astype(np.int64)
    shape = act["vertices"]["shape"]
    u = np.fromfile(os.path.join(src, act["vertices"]["file"]), "<u2").reshape(shape)
    verts = np.asarray(q["offset_m"]) + u.astype(np.float64) * np.asarray(q["scale_m_per_uint"])
    return man, act, faces, verts


# ----------------------------------------------------------------------------------------------- geometry helpers
def signed_volume(v, f):
    import numpy as np
    a, b, c = v[f[:, 0]], v[f[:, 1]], v[f[:, 2]]
    return float(np.einsum("ij,ij->i", a, np.cross(b, c)).sum() / 6.0)


def face_normals(v, f):
    import numpy as np
    n = np.cross(v[f[:, 1]] - v[f[:, 0]], v[f[:, 2]] - v[f[:, 0]])
    return n  # un-normalised (length = 2*area)


def cap_boundary(faces):
    """Close every boundary loop with a zig-zag strip of existing vertices, oriented like its neighbours."""
    import numpy as np
    directed = np.concatenate([faces[:, [0, 1]], faces[:, [1, 2]], faces[:, [2, 0]]])
    key = set(map(tuple, directed.tolist()))
    bnd = [(a, b) for a, b in directed.tolist() if (b, a) not in key]
    nxt = dict(bnd)
    caps, seen = [], set()
    for start in list(nxt):
        if start in seen:
            continue
        loop, cur = [], start
        while cur not in seen:
            seen.add(cur)
            loop.append(cur)
            cur = nxt[cur]
        # polygon order reversed w.r.t. the boundary direction -> cap edges oppose the boundary edges
        poly = [loop[0]] + loop[:0:-1]
        caps.append(poly)
    new = []
    for poly in caps:
        lo, hi, flip = 0, len(poly) - 1, True
        while hi - lo > 1:
            if flip:
                new.append((poly[lo], poly[lo + 1], poly[hi])); lo += 1
            else:
                new.append((poly[lo], poly[hi - 1], poly[hi])); hi -= 1
            flip = not flip
    return np.asarray(new, dtype=np.int64), [len(p) for p in caps], caps


def closest_on(v, f, pts, nthreads=4):
    """Closest points of pts on mesh (v,f): returns (points, tri ids, barycentrics[.,3], dist)."""
    import numpy as np
    import open3d as o3d
    sc = o3d.t.geometry.RaycastingScene()
    sc.add_triangles(o3d.core.Tensor(v.astype(np.float32)), o3d.core.Tensor(f.astype(np.uint32)))
    r = sc.compute_closest_points(o3d.core.Tensor(pts.astype(np.float32)), nthreads=nthreads)
    p = r["points"].numpy().astype(np.float64)
    tri = r["primitive_ids"].numpy().astype(np.int64)
    uv = r["primitive_uvs"].numpy().astype(np.float64)
    bary = np.stack([1 - uv[:, 0] - uv[:, 1], uv[:, 0], uv[:, 1]], 1)
    return p, tri, bary, np.linalg.norm(p - pts, axis=1)


def dist_to(v, f, pts, nthreads=4):
    import numpy as np
    import open3d as o3d
    sc = o3d.t.geometry.RaycastingScene()
    sc.add_triangles(o3d.core.Tensor(v.astype(np.float32)), o3d.core.Tensor(f.astype(np.uint32)))
    return sc.compute_distance(o3d.core.Tensor(pts.astype(np.float32)), nthreads=nthreads).numpy().astype(np.float64)


# ----------------------------------------------------------------------------------------------- build
def build(a):
    import numpy as np
    import open3d as o3d
    import trimesh

    man, act, faces_full, V = load_source(a.src)
    Fsrc, Nv, _ = V.shape
    fps_src = float(act["fps"])
    M = np.load(a.model, allow_pickle=False)
    Jreg, W, vt = M["J_regressor"], M["weights"], M["v_template"]
    assert np.array_equal(M["f"].astype(np.int64), faces_full), "faces do not match SMPL-X model topology"
    stats = {"source": {"frames": Fsrc, "vertices": Nv, "faces": len(faces_full), "fps": fps_src}}

    # ---- 1. orientation: identity, verified from joints
    R = np.eye(3)
    with np.errstate(all="ignore"):   # numpy 2.0 + Accelerate raises spurious FP warnings in matmul
        J0 = Jreg @ V[0]
        V = V @ R.T
    assert np.isfinite(J0).all() and np.isfinite(V).all()
    checks = {
        "left_hip_x_minus_right_hip_x": float(J0[1, 0] - J0[2, 0]),   # >0: +X = subject-left
        "head_y_minus_pelvis_y": float(J0[15, 1] - J0[0, 1]),        # >0: +Y = up
        "nose_z_minus_head_z": float(V[0, 9120, 2] - J0[15, 2]),     # SMPL-X nose-tip vertex; >0: +Z = front
        "toe_z_minus_ankle_z_left": float(J0[10, 2] - J0[7, 2]),     # >0: feet point to +Z
        "pelvis_joint_frame0": J0[0].round(5).tolist(),
    }
    assert checks["left_hip_x_minus_right_hip_x"] > 0 and checks["head_y_minus_pelvis_y"] > 0
    assert checks["nose_z_minus_head_z"] > 0 and checks["toe_z_minus_ankle_z_left"] > 0
    stats["orientation"] = {"rotation": R.tolist(), "checks": checks}

    # ---- 2. body surface: drop eyeballs, cap the mouth
    body = faces_full[(faces_full < N_BODY).all(1)]
    cap, loop_lens, loops = cap_boundary(body)
    surf = np.concatenate([body, cap])       # full-resolution reference surface (body + mouth cap)
    tm = trimesh.Trimesh(V[0, :N_BODY], surf, process=False)
    stats["full_surface"] = {"body_faces": len(body), "cap_faces": len(cap), "hole_loops": loop_lens,
                             "watertight": bool(tm.is_watertight), "winding_consistent": bool(tm.is_winding_consistent),
                             "euler": int(tm.euler_number), "signed_volume_m3_frame0": signed_volume(V[0], surf)}
    assert stats["full_surface"]["signed_volume_m3_frame0"] > 0, "source winding is not CCW-outward"

    # ---- 3. decimate once, on one pose
    P0 = vt if a.pose == "template" else V[a.pose_frame]
    om = o3d.geometry.TriangleMesh(o3d.utility.Vector3dVector(np.ascontiguousarray(P0[:N_BODY], dtype=np.float64)),
                                   o3d.utility.Vector3iVector(np.ascontiguousarray(surf, dtype=np.int32)))
    dm = om.simplify_quadric_decimation(target_number_of_triangles=a.target_tris)
    dm.remove_degenerate_triangles(); dm.remove_duplicated_triangles()
    dm.remove_duplicated_vertices(); dm.remove_unreferenced_vertices(); dm.remove_non_manifold_edges()
    Vd0 = np.asarray(dm.vertices).astype(np.float64)
    Fd = np.asarray(dm.triangles).astype(np.int64)
    if signed_volume(Vd0, Fd) < 0:
        Fd = Fd[:, ::-1].copy()

    # ---- 4. barycentric mapping onto the full surface in the same pose
    cp, tri, bary, d_snap = closest_on(P0[:N_BODY], surf, Vd0)
    bary = np.clip(bary, 0, None); bary /= bary.sum(1, keepdims=True)
    host = surf[tri]                                              # [Vd,3] full-res vertex ids
    def recon(frames):                                            # frames [n, Nv, 3] -> [n, Vd, 3]
        return np.einsum("vk,nvkd->nvd", bary, frames[:, host])
    Rall = recon(V)                                               # every source frame
    Vd = len(Vd0)
    stats["decimation"] = {"pose": a.pose if a.pose == "template" else f"frame{a.pose_frame}",
                           "target_tris": a.target_tris, "V": Vd, "T": len(Fd),
                           "snap_to_surface_mm": {"max": 1e3 * d_snap.max(), "p99": 1e3 * np.percentile(d_snap, 99),
                                                  "mean": 1e3 * d_snap.mean()}}

    # ---- 5. frame selection
    if a.frames == "every2":
        sel = np.arange(0, Fsrc, 2)
        pack = Rall[sel]
        fps = fps_src / 2
        src_times = sel.astype(float)
    else:
        # detect the motion period (source frames) by sub-frame search, resample one period to n frames
        def at(t):
            i0 = np.clip(np.floor(t).astype(int), 0, Fsrc - 2); w = (t - i0)[:, None, None]
            return (1 - w) * Rall[i0] + w * Rall[i0 + 1]
        best = None
        for P in np.arange(a.period_min, a.period_max, 0.01):
            t = np.arange(0, Fsrc - 1 - P)
            e = np.linalg.norm(at(t + P) - Rall[t.astype(int)], axis=2).mean()
            if best is None or e < best[1]:
                best = (float(P), float(e))
        P = best[0]
        src_times = np.arange(a.n_frames) * P / a.n_frames
        pack = at(src_times)
        fps = fps_src * a.n_frames / P
        stats["period"] = {"frames_30fps": P, "seconds": P / fps_src, "mean_mismatch_mm": 1e3 * best[1]}
    F = len(pack)

    def full_frame(k):                                            # full-res vertices at pack frame k
        t = float(src_times[k]); i0 = min(int(np.floor(t)), Fsrc - 2); w = t - i0
        return V[i0] if w == 0 else (1 - w) * V[i0] + w * V[i0 + 1]

    # ---- loop choice: seam vs typical step
    step = np.linalg.norm(pack[1:] - pack[:-1], axis=2).mean(1)
    seam_v = np.linalg.norm(pack[-1] - pack[0], axis=1)
    seam = float(seam_v.mean())
    loop = "cycle" if seam <= 1.5 * float(np.median(step)) else "pingpong"
    if a.loop != "auto":
        loop = a.loop
    stats["loop"] = {"choice": loop, "seam_mean_mm": 1e3 * seam, "seam_max_mm": 1e3 * float(seam_v.max()),
                     "step_mean_mm_median": 1e3 * float(np.median(step)), "step_mean_mm_min": 1e3 * float(step.min()),
                     "step_mean_mm_max": 1e3 * float(step.max()),
                     "step_at_ends_mm": [1e3 * float(step[0]), 1e3 * float(step[-1])]}

    # ---- 6. quantise (per-axis affine over all pack frames)
    lo, hi = pack.reshape(-1, 3).min(0), pack.reshape(-1, 3).max(0)
    scale = (hi - lo) / 65535.0
    qv = np.clip(np.rint((pack - lo) / scale), 0, 65535).astype("<u2")
    deq = lo + qv.astype(np.float64) * scale

    # ---- 7. checks on the decimated mesh
    dmesh = trimesh.Trimesh(deq[0], Fd, process=False)
    ref = np.bincount(Fd.ravel(), minlength=Vd)
    areas = np.stack([np.linalg.norm(face_normals(deq[k], Fd), axis=1) / 2 for k in range(F)])
    vols = [signed_volume(deq[k], Fd) for k in range(F)]
    # normal-agreement check: decimated face normal vs summed normals of the full-res host triangles of its corners
    # (winding is checked topologically above; this flags coarse faces spanning thin features such as ears)
    flips = np.zeros(len(Fd), bool)
    min_dot = 1.0
    for k in range(F):
        hn = face_normals(full_frame(k), surf)[tri][Fd].sum(1); nd = face_normals(deq[k], Fd)
        c = np.einsum("ij,ij->i", hn, nd) / (np.linalg.norm(hn, axis=1) * np.linalg.norm(nd, axis=1) + 1e-30)
        flips |= c < 0; min_dot = min(min_dot, float(c.min()))
    hn = face_normals(P0[:N_BODY], surf)[tri][Fd].sum(1); nd = face_normals(Vd0, Fd)   # raw QEM output, before snapping
    raw_disagree = int((np.einsum("ij,ij->i", hn, nd) < 0).sum())
    e = np.unique(np.sort(np.concatenate([Fd[:, [0, 1]], Fd[:, [1, 2]], Fd[:, [2, 0]]]), 1), axis=0)
    el = np.linalg.norm(deq[:, e[:, 0]] - deq[:, e[:, 1]], axis=2)
    # angles
    def min_angle_deg(v):
        A, B, C = v[Fd[:, 0]], v[Fd[:, 1]], v[Fd[:, 2]]
        def ang(p, q, r):
            u, w = q - p, r - p
            return np.degrees(np.arccos(np.clip(np.einsum("ij,ij->i", u, w) /
                                                (np.linalg.norm(u, axis=1) * np.linalg.norm(w, axis=1)), -1, 1)))
        return np.minimum(np.minimum(ang(A, B, C), ang(B, C, A)), ang(C, A, B))
    minang = min(float(min_angle_deg(deq[k]).min()) for k in range(F))
    stats["checks"] = {
        "watertight": bool(dmesh.is_watertight), "winding_consistent": bool(dmesh.is_winding_consistent),
        "euler": int(dmesh.euler_number), "signed_volume_m3_min_over_frames": float(min(vols)),
        "ccw_outward_all_frames": bool(min(vols) > 0),
        "unreferenced_vertices": int((ref == 0).sum()), "repeated_index_faces": int(((Fd[:, 0] == Fd[:, 1]) | (Fd[:, 1] == Fd[:, 2]) | (Fd[:, 0] == Fd[:, 2])).sum()),
        "min_face_area_mm2_over_frames": 1e6 * float(areas.min()), "min_angle_deg_over_frames": minang,
        "faces_normal_disagree_with_full_any_frame": int(flips.sum()), "min_normal_cos_vs_full": min_dot,
        "faces_normal_disagree_raw_qem_before_snap": raw_disagree,
        "edge_len_ratio_vs_frame0": {"min": float((el / el[0]).min()), "max": float((el / el[0]).max())},
        "edges": len(e),
    }

    # ---- 8. errors vs the full surface, every pack frame (dequantised pack geometry)
    bs = np.array([[1/3, 1/3, 1/3], [.5, .5, 0], [0, .5, .5], [.5, 0, .5], [.6, .2, .2], [.2, .6, .2], [.2, .2, .6],
                   [.8, .1, .1], [.1, .8, .1], [.1, .1, .8]])
    per = {"vertex": [], "face_to_full": [], "full_to_face": []}
    worst = {"face_to_full": (0, None), "full_to_face": (0, None)}
    Wd = np.einsum("vk,vkj->vj", bary, W[host])                # skinning weights of decimated vertices
    for k in range(F):
        Vk = full_frame(k)
        dv = dist_to(Vk[:N_BODY], surf, deq[k])
        pts = np.einsum("sk,tkd->tsd", bs, deq[k][Fd]).reshape(-1, 3)
        df = dist_to(Vk[:N_BODY], surf, pts)
        dr = dist_to(deq[k], Fd, Vk[:N_BODY])
        for nm, d in (("vertex", dv), ("face_to_full", df), ("full_to_face", dr)):
            per[nm].append([1e3 * float(d.max()), 1e3 * float(np.percentile(d, 99)), 1e3 * float(d.mean())])
        if df.max() * 1e3 > worst["face_to_full"][0]:
            fi = int(df.argmax() // len(bs)); worst["face_to_full"] = (1e3 * float(df.max()), [k, part_name(Wd[Fd[fi]].sum(0).argmax())])
        if dr.max() * 1e3 > worst["full_to_face"][0]:
            vi = int(dr.argmax()); worst["full_to_face"] = (1e3 * float(dr.max()), [k, part_name(W[vi].argmax())])
    err = {}
    for nm, rows in per.items():
        r = np.asarray(rows)
        err[nm] = {"max_mm_over_frames": float(r[:, 0].max()), "p99_mm_worst_frame": float(r[:, 1].max()),
                   "p99_mm_median_frame": float(np.median(r[:, 1])), "mean_mm": float(r[:, 2].mean())}
    err["face_to_full"]["worst_at_frame_part"] = worst["face_to_full"][1]
    err["full_to_face"]["worst_at_frame_part"] = worst["full_to_face"][1]
    # per-part breakdown of full->face at worst frame for the report
    k = worst["full_to_face"][1][0]
    dr = dist_to(deq[k], Fd, full_frame(k)[:N_BODY]); parts = np.array([part_name(j) for j in W[:N_BODY].argmax(1)])
    big = dr > 0.005
    err["full_to_face"]["worst_frame_verts_over_5mm_by_part"] = {p: int(n) for p, n in zip(*np.unique(parts[big], return_counts=True))}
    err["full_to_face"]["worst_frame_share_over_5mm"] = float(big.mean())
    err["quantisation_max_mm"] = 1e3 * float(np.linalg.norm(deq - pack, axis=2).max())
    # linear-interpolation error at the skipped source frames (what the viewer shows between pack frames)
    if a.frames == "every2":
        odd = np.arange(1, Fsrc - 1, 2)
        mid = 0.5 * (Rall[odd - 1] + Rall[odd + 1])
        di = np.linalg.norm(mid - Rall[odd], axis=2)
        err["interp_midframe_mm"] = {"max": 1e3 * float(di.max()), "p99": 1e3 * float(np.percentile(di, 99))}
    stats["error"] = err

    # ---- 9. header fields
    # centre: mean (x,z) of the full-resolution SMPL-X pelvis-region vertices (argmax skin weight = pelvis) at
    # pack frame 0 -- independent of where the decimation happened to put vertices
    pel_full = W[:N_BODY].argmax(1) == 0
    centre = full_frame(0)[:N_BODY][pel_full][:, [0, 2]].mean(0)
    pel = Wd.argmax(1) == 0
