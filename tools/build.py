#!/usr/bin/env python3
"""Build dist/<id>.html: one self-contained file that works opened from disk in any browser.
usage: build.py versions/<id>/index.html

1. Hero viewer (a <script type="module"> that does `import * as THREE from 'three'`, plus the
   <script type="importmap"> that maps "three" to shared/assets/vendor/three.module.min.js):
   both are replaced by ONE inline module = three.module.min.js with its single trailing
   `export{a as A,...}` rewritten to `const THREE={A:a,...};`, followed by the viewer (its import
   line removed) inside its own { } block, so three's minified top-level names cannot collide with
   the viewer's. No import map, no module import, no data: URL module is left.
2. Each motion pack (<link ... id="motion-src" href="...">, or id="motion-src-<name>") becomes
   <script type="text/plain" id="motion-data[-<name>]">BASE64</script>; the viewer decodes it with atob, so
   the dist makes no fetch.
3. Every other src=/href=/url() reference to shared/assets/* is inlined as a data: URI, except PDFs: a .pdf is never
   inlined; it is rewritten to assets/papers/<file> and copied to dist/assets/papers/ (the one sidecar of the dist page).
Every assumption (one export block, no imports inside three, one viewer module, unique motion link ids)
is checked; the build exits with a message if one does not hold.
inline_motion() is also used by tools/artifact_files_build.py (the artifact host does not serve .bin files)."""
import sys, os, re, base64, json, shutil
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MIME = {".svg": "image/svg+xml", ".png": "image/png", ".jpg": "image/jpeg", ".jpeg": "image/jpeg",
        ".webp": "image/webp", ".gif": "image/gif", ".mp4": "video/mp4", ".webm": "video/webm",
        ".js": "text/javascript", ".mjs": "text/javascript", ".bin": "application/octet-stream"}
SCRIPT = re.compile(r'<script\b([^>]*)>([\s\S]*?)</script>', re.I)
IMPORT_THREE = re.compile(r'''^[ \t]*import\s*\*\s*as\s+THREE\s+from\s*['"]three['"]\s*;?[ \t]*\n?''', re.M)

def fail(msg): sys.exit("build.py: " + msg)

def resolve(d, ref):
    p = os.path.normpath(os.path.join(d, ref))
    if not os.path.isfile(p): fail(f"missing asset: {ref} -> {p}")
    return p

def merge_three(s, d):
    maps = [m for m in SCRIPT.finditer(s) if re.search(r'''\btype=["']importmap["']''', m.group(1))]
    mods = [m for m in SCRIPT.finditer(s) if re.search(r'''\btype=["']module["']''', m.group(1))]
    if not maps and not mods: return s, None
    if len(maps) != 1 or len(mods) != 1: fail(f"expected one import map and one module script, found {len(maps)} and {len(mods)}")
    imports = json.loads(maps[0].group(2)).get("imports", {})
    if set(imports) != {"three"}: fail(f"the import map may only map 'three', found {sorted(imports)}")
    lib = open(resolve(d, imports["three"]), encoding="utf-8").read()
    if re.search(r'''\bimport\s*[{*("']|import\.meta''', lib): fail("three.module.min.js imports other modules; use a self-contained build")
    if len(re.findall(r'\bexport\b', lib)) != 1: fail("three.module.min.js must contain exactly one export statement")
    ex = re.search(r'\bexport\s*\{([^}]*)\}\s*;?\s*$', lib)
    if not ex: fail("three.module.min.js does not end in one export{...} block")
    pairs = []
    for e in ex.group(1).split(","):
        m = re.fullmatch(r'\s*([\w$]+)(?:\s+as\s+([\w$]+))?\s*', e)
        if not m: fail(f"cannot read export entry {e!r}")
        pairs.append(f"{m.group(2) or m.group(1)}:{m.group(1)}")
    rev = re.search(r'\b([\w$]+) as REVISION\b', ex.group(1))
    rev = re.search(r'\b' + re.escape(rev.group(1)) + r'="(\d+)"', lib).group(1) if rev else "?"
    if re.search(r'\b(?:const|let|var|function|class)\s+THREE\b', lib): fail("three.module.min.js already declares THREE")
    lib = lib[:ex.start()].rstrip() + "\nconst THREE={" + ",".join(pairs) + "};\n"
    viewer = mods[0].group(2)
    if len(IMPORT_THREE.findall(viewer)) != 1: fail("the module must import three exactly as `import * as THREE from 'three';`")
    viewer = IMPORT_THREE.sub("", viewer, count=1)
    if re.search(r'''^\s*import\b|\bimport\s*\(''', viewer, re.M): fail("the module has another import")
    for t in (lib, viewer):
        if re.search(r'</script|<!--', t, re.I): fail("script text contains </script or <!--")
    note = (f"/* Generated by tools/build.py from three.js r{rev} (shared/assets/vendor/three.module.min.js, MIT;"
            f" its export block rewritten to `const THREE={{...}}`, {len(pairs)} names) followed by the hero viewer"
            " in its own block. No import map, no module import, no fetch. */\n")
    merged = f'<script type="module">\n{note}{lib}{{\n{viewer.strip()}\n}}\n</script>'
    a, b = sorted([maps[0], mods[0]], key=lambda m: m.start())   # replace the later one first
    later = merged if b is mods[0] else ""
    earlier = merged if a is mods[0] else ""
    s = s[:b.start()] + later + s[b.end():]
    s = s[:a.start()] + earlier + re.sub(r'^\n', '', s[a.end():], count=1)
    return s, (rev, len(pairs), len(lib))

def inline_motion(s, d):
    """every <link id="motion-src"> / <link id="motion-src-<name>"> becomes <script type="text/plain" id="motion-data[-<name>]">"""
    links = re.findall(r'''<link\b[^>]*\bid=["']motion-src(?:-[\w]+)?["'][^>]*>''', s)
    if not links: return s, None
    ids = [re.search(r'''\bid=["'](motion-src(?:-[\w]+)?)["']''', l).group(1) for l in links]
    if len(set(ids)) != len(ids): fail("duplicate motion-src link ids")
    total = 0
    for l, i in zip(links, ids):
        href = re.search(r'''\bhref=["']([^"']+)["']''', l)
        if not href: fail(f"{i} link has no href")
        raw = open(resolve(d, href.group(1)), "rb").read(); total += len(raw)
        block = f'<script type="text/plain" id="{i.replace("motion-src", "motion-data")}">' + base64.b64encode(raw).decode() + '</script>'
        s = s.replace(l, block, 1)
    return s, total

def main(pages):
    for page in pages:
        page = os.path.abspath(page); d = os.path.dirname(page)
        s = open(page, encoding="utf-8").read()
        s, three = merge_three(s, d)
        s, pack = inline_motion(s, d)
        sidecars = []
        def inline(m):
            p = resolve(d, m.group(2))
            if p.lower().endswith(".pdf"):   # PDFs are linked, never inlined: copy beside the dist page
                dst = os.path.join(root, "dist", "assets", "papers", os.path.basename(p))
                os.makedirs(os.path.dirname(dst), exist_ok=True); shutil.copy2(p, dst); sidecars.append(dst)
                return m.group(1) + "assets/papers/" + os.path.basename(p) + m.group(3)
            mime = MIME.get(os.path.splitext(p)[1].lower(), "application/octet-stream")
            return m.group(1) + f"data:{mime};base64," + base64.b64encode(open(p, "rb").read()).decode() + m.group(3)
        s = re.sub(r'''((?:src|href)=["']|url\(["']?)([^"')]*shared/assets/[^"')]+)(["')])''', inline, s)
        # a preload of in-document bytes is meaningless, and Chromium warns that it is never used
        s = re.sub(r'''<link\b[^>]*\bhref=["']data:[^>]*>''', lambda m: re.sub(r'''\brel=["']preload["']''', 'rel="prefetch"', m.group(0)), s)
        os.makedirs(os.path.join(root, "dist"), exist_ok=True)
        out = os.path.join(root, "dist", os.path.basename(d) + ".html")
        open(out, "w", encoding="utf-8").write(s)
        extra = []
        if three: extra.append(f"three r{three[0]} merged ({three[1]} exports, {three[2] // 1024} KB)")
        if pack: extra.append(f"motion pack inlined ({pack // 1024} KB)")
        for f in sorted(set(sidecars)): extra.append(f"sidecar {os.path.relpath(f, os.path.join(root, 'dist'))} ({os.path.getsize(f) // 1024} KB)")
        print("built", out, len(s) // 1024, "KB" + ("; " + "; ".join(extra) if extra else ""))

if __name__ == "__main__":
    main(sys.argv[1:])
